#!/usr/bin/env node
/**
 * Generate Tailwind v4 variants for a component package's public anatomy.
 *
 * Tokens and utilities belong to @mash/tokens. This adapter is deliberately
 * generated from custom-elements.json so slots, parts, and custom states have
 * one source of truth and cannot drift from the catalogue or wrapper tooling.
 */

import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const PACKAGE_ROOT = process.cwd();
const MANIFEST = path.join(PACKAGE_ROOT, "custom-elements.json");
const OUTPUT = path.join(PACKAGE_ROOT, "dist", "tailwind.css");
const SAFE_NAME = /^[a-z][a-z0-9-]*$/;

function declarationsIn(manifest) {
  return (manifest.modules ?? [])
    .flatMap((module) => module.declarations ?? [])
    .filter((declaration) => declaration.customElement && declaration.tagName);
}

function namesFrom(declarations, key) {
  return [
    ...new Set(
      declarations.flatMap((declaration) =>
        (declaration[key] ?? [])
          .map((entry) => entry.name)
          .filter((name) => name && SAFE_NAME.test(name)),
      ),
    ),
  ].sort((left, right) => left.localeCompare(right));
}

function renderVariants(manifest, packageName) {
  const declarations = declarationsIn(manifest);
  const parts = namesFrom(declarations, "cssParts");
  const slots = namesFrom(declarations, "slots");
  const states = namesFrom(declarations, "cssStates");

  const partVariants = parts.map((name) => `@custom-variant part-${name} (&::part(${name}));`);
  const slotVariants = slots.map((name) => `@custom-variant slot-${name} (& > [slot="${name}"]);`);
  const stateVariants = states.map((name) => `@custom-variant state-${name} (&:state(${name}));`);

  return `/**
 * Generated by scripts/build-tailwind-components.mjs. Do not edit.
 *
 * Tailwind CSS v4 component adapter for ${packageName}.
 * Import this after \`tailwindcss\` and \`@mash/tokens/tailwind.css\`.
 *
 * - \`part-root:bg-surface\` styles a published shadow part.
 * - \`slot-prefix:text-muted\` styles authored content in a named slot.
 * - \`state-open:opacity-motion-visible\` responds to a published custom state.
 */

${partVariants.join("\n")}

${slotVariants.join("\n")}

${stateVariants.join("\n")}
`;
}

const manifest = JSON.parse(await readFile(MANIFEST, "utf8"));
const packageJson = JSON.parse(await readFile(path.join(PACKAGE_ROOT, "package.json"), "utf8"));
await mkdir(path.dirname(OUTPUT), { recursive: true });
await writeFile(OUTPUT, renderVariants(manifest, packageJson.name));
