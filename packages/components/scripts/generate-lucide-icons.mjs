#!/usr/bin/env node
/** Generate Mash's curated Lucide registry as inert SVG strings.
 * Only the selected glyphs ship in the runtime; lucide-static is a build dependency.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const packageRoot = fileURLToPath(new URL("..", import.meta.url));
const lucideRoot = path.dirname(require.resolve("lucide-static/package.json"));
const { version } = JSON.parse(await readFile(path.join(lucideRoot, "package.json"), "utf8"));
const license = await readFile(path.join(lucideRoot, "LICENSE"), "utf8");
const output = path.join(packageRoot, "src/icon/lucide-icons.generated.ts");
const sizes = [16, 20, 24];

const icons = {
  "action.add": "plus",
  "action.confirm": "check",
  "action.delete": "trash-2",
  "action.dismiss": "x",
  "action.drag": "grip-vertical",
  "action.duplicate": "copy",
  "action.edit": "pencil",
  "action.bring-forward": "bring-to-front",
  "action.connect": "plug",
  "action.link": "link",
  "action.fit": "maximize",
  "action.frame": "frame",
  "action.launch": "external-link",
  "action.pan": "hand",
  "action.pause": "pause",
  "action.play": "play",
  "action.refresh": "refresh-cw",
  "action.remove": "minus",
  "action.reset": "rotate-ccw",
  "action.search": "search",
  "action.select": "mouse-pointer-2",
  "action.settings": "settings",
  "action.text": "type",
  "action.upload": "upload",
  "action.download": "download",
  "navigation.back": "arrow-left",
  "navigation.chevron-left": "chevron-left",
  "navigation.panel-left": "panel-left",
  "navigation.panel-right": "panel-right",
  "navigation.chevron-down": "chevron-down",
  "navigation.disclosure": "chevron-right",
  "navigation.down": "arrow-down",
  "navigation.forward": "arrow-right",
  "navigation.menu": "menu",
  "navigation.more.horizontal": "ellipsis",
  "navigation.more.vertical": "ellipsis-vertical",
  "navigation.up": "arrow-up",
  "object.document": "file-text",
  "object.bookmark": "bookmark",
  "object.clock": "clock",
  "object.code": "code",
  "object.tree": "list-tree",
  "object.audio": "music",
  "object.folder": "folder",
  "object.image": "image",
  "object.keyboard": "keyboard",
  "object.layers": "layers",
  "object.table": "table",
  "object.terminal": "terminal",
  "object.video": "video",
  "status.error": "circle-alert",
  "status.information": "info",
  "status.loading": "refresh-cw",
  "status.warning": "triangle-alert",
};

async function glyph(slug) {
  const source = await readFile(path.join(lucideRoot, "icons", `${slug}.svg`), "utf8");
  return source
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\sclass="[^"]*"/, "")
    .replace(/width="24"/, 'width="1em"')
    .replace(/height="24"/, 'height="1em"')
    .replace("<svg", '<svg part="source" aria-hidden="true" focusable="false"')
    .replace(/\s+/g, " ")
    .trim();
}

const entries = [];
for (const [name, slug] of Object.entries(icons)) {
  const source = await glyph(slug);
  const variants = sizes.map((size) => `      ${size}: ${JSON.stringify(source)},`);
  entries.push(`  ${JSON.stringify(name)}: {\n${variants.join("\n")}\n    },`);
}

const source = `/**
 * Generated by scripts/generate-lucide-icons.mjs from lucide-static ${version}.
 * Do not edit. Lucide and Feather license notices follow.
 *
${license
  .trim()
  .split("\n")
  .map((line) => ` * ${line}`.trimEnd())
  .join("\n")}
 */

export const lucideIcons = Object.freeze({
${entries.join("\n")}
} as const);
`;

await mkdir(path.dirname(output), { recursive: true });
await writeFile(output, source);
console.log(`generated ${path.relative(packageRoot, output)} (${entries.length} semantic icons)`);
