const escape = (value) =>
  String(value)
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");

const attrs = (attributes = {}) =>
  Object.entries(attributes)
    .filter(([name]) => name !== "width" && name !== "height")
    .map(([name, value]) => ` ${name}="${escape(value)}"`)
    .join("");

function nodeMarkup(node) {
  const children = (node.content ?? []).map(nodeMarkup).join("");
  return `<${node.elem}${attrs(node.attrs)}>${children}</${node.elem}>`;
}

async function glyph(slug, size) {
  const module = await import(`@carbon/icons/es/${slug}/${size}.js`);
  const descriptor = module.default;
  const children = descriptor.content.map(nodeMarkup).join("");
  return `<svg part="source" xmlns="http://www.w3.org/2000/svg" viewBox="${descriptor.attrs.viewBox}" fill="currentColor" width="1em" height="1em" aria-hidden="true" focusable="false">${children}</svg>`;
}

const entries = [];
for (const [name, slug] of Object.entries(icons)) {
  const variants = [];
  for (const size of sizes)
    variants.push(`      ${size}: ${JSON.stringify(await glyph(slug, size))},`);
  entries.push(`  ${JSON.stringify(name)}: {\n${variants.join("\n")}\n    },`);
}

const source = `/**
 * Generated by scripts/generate-carbon-icons.mjs from @carbon/icons 11.86.0.
 * Do not edit. Carbon icons are Copyright IBM Corp. and licensed Apache-2.0.
 */

export const carbonIcons = Object.freeze({
${entries.join("\n")}
} as const);
`;

await mkdir(path.dirname(output), { recursive: true });
await writeFile(output, source);
console.log(`generated ${path.relative(packageRoot, output)} (${entries.length} semantic icons)`);
